"""Generate the MECHANISM → CODE → TEST → RESULT map for an audit snapshot.

WHY (2026-10-26, audit folder). An auditor who wants to check one mechanism needs four places at once: where the flag
is defined (with its provenance comment), where the model READS it (the behaviour), which tests exercise it, and which
RESULTS entries measured it. This tool finds all four by text search and writes one table. Line numbers are valid for
the commit the audit folder names; regenerate after any code change.

Run:  py -3 tools/gen_code_map.py --out audit/2026-10-26/MAP_mechanisms_to_code.md
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "sic_games" / "src" / "sic_games"
HARNESS = [ROOT / "sic_games" / "outputs" / "substrate_run" / "run_campaign.py",
           ROOT / "sic_games" / "outputs" / "phase1_social_evolution" / "run_se0_controlled_climate.py"]
TESTS = ROOT / "sic_games" / "tests"
RESULTS = ROOT / "docs" / "RESULTS.md"


def entry_index():
    """line -> the RESULTS entry id that contains it (R-NN / Addendum NN headings; Addenda 1-41 have none)."""
    ids, cur = [], "preamble"
    for line in RESULTS.read_text(encoding="utf-8").split("\n"):
        m = re.match(r"^#{2,3} (R-\d+[a-z]?|Addendum \d+)", line)
        if m:
            cur = m.group(1).replace("Addendum ", "Add.")
        ids.append(cur)
    return ids


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    run = tomllib.load(open(ROOT / "config" / "runs" / "full_campaign.toml", "rb"))["mechanisms"]
    src_files = sorted(SRC.rglob("*.py"))
    src_lines = {p: p.read_text(encoding="utf-8").split("\n") for p in src_files}
    harn_lines = {p: p.read_text(encoding="utf-8").split("\n") for p in HARNESS}
    test_text = {p.name: p.read_text(encoding="utf-8") for p in sorted(TESTS.glob("test_*.py"))}
    res_lines = RESULTS.read_text(encoding="utf-8").split("\n")
    eidx = entry_index()
    rel = lambda p: p.relative_to(ROOT).as_posix()
    L = ["# MAP — every mechanism flag → its definition, the code that reads it, its tests, and its RESULTS entries",
         "", "> GENERATED by `tools/gen_code_map.py` for this audit snapshot. Line numbers are valid at the commit named in",
         "> `00_START_HERE.md`. \"reads\" = every non-definition line in `sic_games/src/sic_games/` that names the flag; "
         "\"harness\" = the canon builders (`run_campaign.py`, `run_se0_controlled_climate.py`). RESULTS entries: the R-/",
         "> Addendum entries whose text names the flag (Addenda 1–41 have no headings and show as `R-106`).", "",
         f"{len(run)} flags; {sum(run.values())} ON in canon.", "",
         "| flag | canon | defined at | read at (model code) | harness | tests naming it | RESULTS entries |",
         "|---|---|---|---|---|---|---|"]
    for f in sorted(run):
        pat = re.compile(r"\b" + re.escape(f) + r"\b")
        defined, reads = [], []
        for p, lines in src_lines.items():
            for i, l in enumerate(lines, 1):
                if not pat.search(l):
                    continue
                if re.match(r"\s*" + re.escape(f) + r"\s*:", l):
                    defined.append(f"`{p.name}:{i}`")
                elif not l.strip().startswith("#"):
                    reads.append(f"`{p.name}:{i}`")
        harn = [f"`{p.name}:{i}`" for p, lines in harn_lines.items() for i, l in enumerate(lines, 1)
                if pat.search(l) and not l.strip().startswith("#")]
        tests = [n for n, t in test_text.items() if pat.search(t)]
        ents = []
        for i, l in enumerate(res_lines):
            if pat.search(l) and eidx[i] not in ents:
                ents.append(eidx[i])
        short = lambda xs, k: (", ".join(xs[:k]) + (f" … (+{len(xs) - k})" if len(xs) > k else "")) or "—"
        L.append(f"| `{f}` | {'**ON**' if run[f] else 'off'} | {short(defined, 2)} | {short(reads, 4)} | "
                 f"{short(harn, 2)} | {short(tests, 3)} | {short(ents, 6)} |")
    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("wrote", rel(out))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
