"""The derived audit registries must match a fresh generation (2026-10-26, audit preparation).

`docs/REGISTRY.md` (every flag and parameter of the canonical run) and `docs/RESULTS_INDEX.md` (every RESULTS entry)
are GENERATED by `tools/gen_registry.py` from the config, the code, the audit tables and RESULTS.md. A stale copy
would tell an auditor a wrong canon state, so this test fails until `py -3 tools/gen_registry.py` is re-run.
Imported, not run as a subprocess, so it is immune to the WinError 6 stdin artifact of the subprocess tests.
"""
import importlib.util
import os

_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
_spec = importlib.util.spec_from_file_location("gen_registry", os.path.join(_ROOT, "tools", "gen_registry.py"))
gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen)


def _committed(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def test_registry_is_current():
    assert _committed(gen.OUT_REG) == gen.build_registry(), "docs/REGISTRY.md is stale: run py -3 tools/gen_registry.py"


def test_results_index_is_current():
    assert _committed(gen.OUT_RES) == gen.build_results_index(), \
        "docs/RESULTS_INDEX.md is stale: run py -3 tools/gen_registry.py"


def test_every_canonical_flag_is_in_the_registry():
    import tomllib
    with open(os.path.join(_ROOT, "config", "runs", "full_campaign.toml"), "rb") as fh:
        flags = tomllib.load(fh)["mechanisms"]
    reg = _committed(gen.OUT_REG)
    missing = [f for f in flags if f"`{f}`" not in reg]
    assert not missing, missing
